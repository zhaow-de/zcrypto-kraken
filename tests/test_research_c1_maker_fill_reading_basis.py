@pytest.mark.skipif(
    nothing_found_under(_DATA_ROOT, "l2-fills-*/*/*/*/*/*.parquet"), reason="the frozen l2-fills set is absent under data/"
)
def test_the_inputs_half_reads_the_sets_measured_basis():
    assert _DATA_ROOT == research_command._DATA_ROOT
    provenance, frames = subjects._c1_reads(ObservedReader(_DATA_ROOT), DATASET, SUBJECT)
    coverage = subjects._c1_reading_inputs({p: f.select(subjects._C1_INPUT_COLUMNS) for p, f in frames.items()}, provenance)
    assert (provenance["params"], provenance["code_ref"]) == (PARAMS, CODE_REF)
    assert sorted(coverage) == sorted(COUNTS)
    for pair, got in coverage.items():
        entries = provenance["pairs"][pair].values()
        no_quote, stale, overlay_book, overlay_trades = COUNTS[pair]
        posts = sum(cell["posts"] for month in got["months"].values() for cell in month.values())
        assert (got["days"], got["hours_absent"], got["hours_unanchored"]) == (86, 0, 0), pair
        assert (got["skipped_no_quote"], got["skipped_stale"]) == (no_quote, stale), pair
        assert posts + no_quote + stale == POSTS_PER_HOUR * (SPAN_HOURS - got["hours_unanchored"]), pair
        assert sorted(hour for entry in entries for hour in entry["trades_absent"]) == TRADES_ABSENT[pair], pair
        assert got["trades_absent"] == len(TRADES_ABSENT[pair]), pair
        assert sum(len(entry["book_reconciled"]) for entry in entries) == overlay_book, pair
        assert sum(len(entry["trades_reconciled"]) for entry in entries) == overlay_trades, pair
        for month, cells in MONTHS[pair].items():
            for key, (n, queue_mean, spread_mean) in cells.items():
                cell = got["months"][month][key]
                assert (cell["posts"], cell["stale_seconds_null"]) == (n, 0), (pair, month, key)
                assert cell["queue_ahead_notional_mean"] == pytest.approx(queue_mean, rel=1e-12), (pair, month, key)
                assert cell["spread_at_post_bps_mean"] == pytest.approx(spread_mean, rel=1e-12), (pair, month, key)
